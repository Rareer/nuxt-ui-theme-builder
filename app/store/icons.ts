function toPack(icon: string, pack: string): string {
	// Accept both "lucide:menu" and "i-lucide-menu"
	if (icon.includes(':')) {
		const [, name] = icon.split(':');
		return `${pack}:${name}`;
	}
	const trimmed = icon.replace(/^i-/, '');
	const name = trimmed.split('-').slice(1).join('-');
	return `${pack}:${name}`;
}

export const useIconsStore = defineStore('icons', {
	state: () => ({
		icons: { ...DEFAULT_ICONS } as IconMap,
		selectedPreset: 'lucide',
	}),
	getters: {
		getIcons(state): IconMap {
			return state.icons;
		},
		getSelectedPreset(state): string {
			return state.selectedPreset;
		},
	},
	actions: {
		setIcon(key: string, value: string) {
			this.icons[key] = value;
		},
		resetIcons() {
			this.icons = { ...DEFAULT_ICONS };
			this.selectedPreset = 'lucide';
		},
		applyPreset(pack: string) {
			if (!pack) return;
			const preset = PRESET_MAPS[pack];
			if (preset) {
				// Fallback to default icons where the pack does not provide a specific glyph
				this.icons = { ...DEFAULT_ICONS, ...preset };
			}
			else {
				const next: IconMap = {};
				Object.entries(DEFAULT_ICONS).forEach(([key, value]) => {
					next[key] = toPack(value, pack);
				});
				this.icons = next;
			}
			this.selectedPreset = pack;
		},
	},
});
